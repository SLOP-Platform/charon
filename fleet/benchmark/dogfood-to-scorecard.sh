#!/usr/bin/env bash
# dogfood-to-scorecard.sh — maps a Path-C dogfood-eval SUMMARY.md into
# model-scorecard.tsv `source=live` append commands, WITHOUT ever writing the
# ledger itself. model-scorecard.tsv is owned by the bench-grader integrity
# user (this tool's caller cannot write it and sudo is deny-listed — see
# fleet/state/scorecard-append-2026-07-13.sh for the established pattern this
# mirrors), so this tool only GENERATES a runnable append-script that the
# operator runs as:  sudo -u bench-grader bash <generated-file>
#
# Interfaces confirmed by reading real code before writing this:
#   fleet/model-scorecard.sh cmd_append (line ~42-91): positional order is
#     append <date> <source> <ref> <work_class> <tier> <model> <verdict> \
#            <gate> <score> <time_s> <cost_usd> <corrections> <note...>
#     VALID_VERDICT="MERGE FIXES BLOCK"   VALID_GATE="pass fail -"
#     stage rides in env var CHARON_SCORECARD_STAGE (default "active"; must
#     be one of VALID_STAGE="provisional active").
#   fleet/benchmark/dogfood-eval.sh: SUMMARY.md table columns (line ~103) are
#     | model | verdict | attribution | wall_s | budget_s | gate | ticket-test | diff | scope | card |
#   attribution values seen in dogfood-eval.sh's own classification (~line
#   156-185): ran-to-completion, too-slow(...), provider-degraded->retry(...),
#   provider-throttled->try-another(...), error-nonlimit(...),
#   early-ditch/quality(...), or (a separate early-bailout path) worktree-create-failed.
#
# STAGE (#20 BENCH-PROVISIONAL-SCORING / fail-closed design): every row this
# tool emits is stage=provisional. Path-C dogfood probes are COLLECTED but
# must NOT count toward live grades until a human diff-confirms the run and
# promotes it — matches grades.py's stage==active gate. To promote after
# review, either re-append the same row with CHARON_SCORECARD_STAGE=active,
# or use benchmark/promote.py if/when it grows a scorecard-row mode; there is
# no bulk auto-promote here by design (promotion is a human, not this tool).
#
# This tool NEVER writes model-scorecard.tsv, NEVER writes tier-models.tsv,
# and NEVER runs the generated append-script itself.
#
# Usage: dogfood-to-scorecard.sh <SUMMARY.md> --ticket <LABEL> --work-class <wc>
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FLEET="$(cd "$HERE/.." && pwd)"

die() { echo "error: $*" >&2; exit 1; }

SUMMARY="${1:-}"
[ -n "$SUMMARY" ] && [ -f "$SUMMARY" ] || die "usage: $0 <SUMMARY.md> --ticket <LABEL> --work-class <wc>"
shift

TICKET=""
WORK_CLASS=""
while [ $# -gt 0 ]; do
  case "$1" in
    --ticket) TICKET="${2:-}"; shift 2 ;;
    --work-class) WORK_CLASS="${2:-}"; shift 2 ;;
    *) die "unknown arg: $1" ;;
  esac
done
[ -n "$TICKET" ] || die "--ticket <LABEL> is required"
[ -n "$WORK_CLASS" ] || die "--work-class <wc> is required"

VALID_CLASS="money-path routing ci-infra refactor bugfix tests greenfield-feature docs frontend"
case " $VALID_CLASS " in *" $WORK_CLASS "*) ;; *) die "work_class must be one of: $VALID_CLASS" ;; esac

DATE="$(date -u +%Y-%m-%d)"
TS="$(date -u +%Y%m%d-%H%M%S)"
OUT="$FLEET/state/scorecard-append-pathc-${TS}-$$.sh"
[ ! -f "$OUT" ] || die "output file already exists (same-second + same-PID collision): $OUT"
S_PATH="$FLEET/model-scorecard.sh"

# ---- classify one dogfood row into a scorecard verdict, or SKIP ----
# args: attribution gate(dogfood gate_verdict) test_v(ticket-test) diffcol
# echoes: "MERGE" | "FIXES" | "BLOCK" | "SKIP"
classify() {
  local attribution="$1" gate="$2" test_v="$3" diffcol="$4"
  case "$attribution" in
    too-slow*) echo BLOCK; return ;;
    provider-*|error-nonlimit*) echo SKIP; return ;;
  esac
  case "$attribution" in
    ran-to-completion*)
      if [ "$gate" = "pass" ] && [ "$test_v" = "pass" ] && [[ "$diffcol" == *real-diff* ]]; then
        echo MERGE
      elif [[ "$diffcol" == *real-diff* ]]; then
        # Produced a GENUINE diff but failed the gate/test (e.g. a lint nit while the
        # logic is correct) — that is FIXES-NEEDED, NOT a detention-feeding BLOCK.
        # BLOCK is reserved for "ran but produced nothing usable" (below).
        echo FIXES
      else
        echo BLOCK
      fi
      ;;
    early-ditch*) echo BLOCK ;;   # ran, produced NO usable diff — genuine model-quality fail
    *) echo BLOCK ;;              # e.g. worktree-create-failed / unknown
  esac
}

# dogfood_gate_verdict -> scorecard VALID_GATE ("pass fail -")
map_gate() {
  case "$1" in
    pass) echo pass ;;
    fail) echo fail ;;
    *) echo "-" ;;   # e.g. "skipped"
  esac
}

: > "$OUT"
{
  echo "#!/usr/bin/env bash"
  echo "# GENERATED by dogfood-to-scorecard.sh from $SUMMARY on $DATE (UTC)."
  echo "# ledger is owned by the bench-grader integrity user; run this as that user:"
  echo "#   sudo -u bench-grader bash $OUT"
  echo "# All rows below are stage=provisional (Path-C probes are collected, not yet"
  echo "# promoted — see #20 fail-closed design). After a human diff-reviews a run and"
  echo "# wants it to count toward live grades, re-run the matching append line with"
  echo "# CHARON_SCORECARD_STAGE=active instead of provisional. This file never"
  echo "# auto-promotes anything."
  echo "set -euo pipefail"
  echo "S=$S_PATH"
  echo "export CHARON_SCORECARD_STAGE=provisional"
  echo
} >> "$OUT"

echo "=== dogfood-to-scorecard: $SUMMARY -> $OUT ==="
n_merge=0 n_fixes=0 n_block=0 n_skip=0

trim() { local s="$1"; s="${s#"${s%%[![:space:]]*}"}"; s="${s%"${s##*[![:space:]]}"}"; printf '%s' "$s"; }

while IFS= read -r line; do
  # only data rows: start with '|', not the header, not the '|---|' separator
  case "$line" in
    '|'*) ;;
    *) continue ;;
  esac
  case "$line" in
    *'| model '*'| verdict '*) continue ;;   # header
  esac
  # separator row is only pipes/dashes/colons/spaces
  stripped="${line//[-|: ]/}"
  [ -z "$stripped" ] && continue

  # split on '|', trim whitespace on each field; first/last split are empty
  # (leading/trailing pipe). Column 2 (overall dogfood verdict, e.g.
  # "REVIEW-READY(...)") is discarded here — the scorecard verdict is
  # RE-derived from attribution/gate/ticket-test/diff per classify(), not
  # copied from dogfood's own advisory overall column.
  IFS='|' read -r _ f_model _ f_attr f_wall _ f_gate f_test f_diff f_scope f_card _ <<< "$line"
  model="$(trim "$f_model")"; attribution="$(trim "$f_attr")"
  wall_s="$(trim "$f_wall")"; gate_col="$(trim "$f_gate")"; test_col="$(trim "$f_test")"
  diff_col="$(trim "$f_diff")"; scope_col="$(trim "$f_scope")"; card_col="$(trim "$f_card")"
  [ -n "$model" ] || continue

  decision="$(classify "$attribution" "$gate_col" "$test_col" "$diff_col")"
  gate_mapped="$(map_gate "$gate_col")"
  note="path-c dogfood $TICKET; attribution=$attribution; scope=$scope_col; card=$card_col"

  case "$decision" in
    SKIP)
      n_skip=$((n_skip+1))
      {
        echo "# SKIPPED (provider-fault — re-run, not a model verdict): model=$model attribution=$attribution"
      } >> "$OUT"
      echo "SKIP  model=$model attribution=$attribution (provider-fault; re-run, not appended)"
      ;;
    MERGE|FIXES|BLOCK)
      case "$decision" in MERGE) n_merge=$((n_merge+1));; FIXES) n_fixes=$((n_fixes+1));; BLOCK) n_block=$((n_block+1));; esac
      # shellcheck disable=SC2016  # literal $S is intentional: written into the
      # generated script for it to expand there, not expanded here.
      printf 'bash "$S" append %s live %s %s - %s %s %s - %s - - %q\n' \
        "$DATE" "$TICKET" "$WORK_CLASS" "$model" "$decision" "$gate_mapped" "$wall_s" "$note" >> "$OUT"
      echo "$decision  model=$model gate=$gate_mapped time_s=$wall_s -> queued in $OUT"
      ;;
  esac
done < "$SUMMARY"

{
  echo
  echo "echo \"DONE (path-c $TICKET): now review, then optionally: bash \$S render\""
} >> "$OUT"
chmod +x "$OUT"

echo "---"
echo "generated: $OUT  (merge=$n_merge fixes=${n_fixes:-0} block=$n_block skip=$n_skip)"
echo "this tool did NOT run it. to apply (stage=provisional, no live-grade impact until promoted):"
echo "  sudo -u bench-grader bash $OUT"
